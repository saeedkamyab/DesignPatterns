using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Liskov_Substitution_Principle.Example2.without
{
	public class WithoutLsp
	{

		/*
		 * حالا اگر کد زیر را بنویسیم و بخواهیم به جای Bird از Penguin استفاده کنیم، برنامه خطا می‌دهد، چون پنگوئن نمی‌تواند پرواز کند.
		 */
		Bird sparrow = new Sparrow();

		Bird penguin = new Penguin();
		
		public void LetBirdFly(Bird bird)
		{
			bird.Fly();
		}
		public void doIt()
		{
			LetBirdFly(sparrow); // خروجی: Flying!
			LetBirdFly(penguin); // خطا: NotImplementedException
		}
		// استفاده از تابع LetBirdFly
		
	}
	/*
	 این متن به **Liskov Substitution Principle** (اصل جانشینی لیسکوف) در SOLID اشاره دارد و توضیح می‌دهد که چگونه زیرکلاس‌ها باید رفتارهای کلاس پایه را رعایت کنند تا بتوانند جایگزین آن‌ها شوند بدون این‌که عملکرد کد دچار مشکل شود. برای رعایت این اصل، زیرکلاس‌ها باید طوری طراحی شوند که با همان قراردادهای کلاس پایه هماهنگ باشند. به این ترتیب، اشیای زیرکلاس می‌توانند به‌جای کلاس پایه استفاده شوند، بدون اینکه عملکرد کد خراب شود.

بیایید توضیح قسمت‌های اصلی این متن را بررسی کنیم:

### ۱. **نوع پارامترها**
   - **توضیح**: نوع پارامترهای یک متد در زیرکلاس باید با نوع پارامترهای کلاس پایه **یکی باشد یا انتزاعی‌تر** باشد. 
   - **مثال**:
     - فرض کنید متد `feed(Cat c)` در کلاس پایه برای تغذیه‌ی گربه‌ها است. اگر زیرکلاسی ایجاد کنیم که نوع پارامترش را به `feed(Animal c)` تغییر دهد، این کار مجاز است، زیرا هر گربه‌ای یک حیوان است. 
     - اما اگر پارامتر را به `feed(BengalCat c)` تغییر دهیم، در این حالت دیگر نمی‌توانیم از این زیرکلاس به‌جای کلاس پایه استفاده کنیم، چون فقط نژاد خاصی از گربه‌ها را می‌پذیرد و کد دیگر کار نخواهد کرد.

### ۲. **نوع بازگشتی**
   - **توضیح**: نوع بازگشتی یک متد در زیرکلاس باید با نوع بازگشتی کلاس پایه **یکسان یا یک زیرنوع** باشد.
   - **مثال**:
     - فرض کنید متد `buyCat()` در کلاس پایه، یک `Cat` را برمی‌گرداند. اگر زیرکلاسی این متد را به شکلی تغییر دهد که یک `BengalCat` را برگرداند، مشکلی پیش نمی‌آید چون `BengalCat` یک زیرنوع از `Cat` است. 
     - اما اگر زیرکلاس متد را به شکلی تغییر دهد که یک `Animal` برگرداند، مشکلاتی به‌وجود می‌آید؛ زیرا اکنون کد ممکن است یک حیوان دیگر (مثلاً یک تمساح یا خرس) دریافت کند، که مناسب نیست.

### ۳. **انواع استثناها**
   - **توضیح**: یک متد در زیرکلاس نباید استثناهایی از نوعی که در متد کلاس پایه وجود ندارد، پرتاب کند.
   - **مثال**: اگر متد کلاس پایه هیچ استثنایی پرتاب نمی‌کند، زیرکلاس هم نباید استثنا جدیدی را معرفی کند، چون کد کاربر ممکن است نتواند آن را مدیریت کند.

### ۴. **پیش‌شرط‌ها و پس‌شرط‌ها**
   - **پیش‌شرط‌ها**: زیرکلاس نباید پیش‌شرط‌های کلاس پایه را سخت‌تر کند. مثلاً اگر کلاس پایه یک پارامتر عددی دریافت می‌کند و محدودیتی روی مثبت بودن عدد نمی‌گذارد، زیرکلاس نباید الزام کند که این عدد حتماً مثبت باشد.
   - **پس‌شرط‌ها**: زیرکلاس نباید پس‌شرط‌ها را ضعیف کند. مثلاً اگر متدی در کلاس پایه همیشه بعد از اجرای خود، اتصال‌های باز با پایگاه داده را می‌بندد، زیرکلاس نیز باید این شرط را رعایت کند.

### ۵. **حفظ شرایط ثابت (Invariants)**
   - **توضیح**: زیرکلاس‌ها باید شرایط ثابت کلاس پایه را حفظ کنند. این به معنی آن است که خصوصیات اساسی که یک شی از کلاس پایه را معتبر می‌سازد، نباید در زیرکلاس نقض شوند.
   - **مثال**: اگر کلاس پایه `Cat` باشد، فرضیات اولیه شامل ویژگی‌هایی مانند تعداد پاها و توانایی میو کردن هستند که در زیرکلاس نیز باید حفظ شوند.

### ۶. **عدم تغییر مقادیر فیلدهای خصوصی**
   - **توضیح**: زیرکلاس‌ها نباید مستقیماً مقادیر فیلدهای خصوصی کلاس پایه را تغییر دهند. 
   - **مثال**: بعضی زبان‌ها اجازه می‌دهند با استفاده از Reflection به فیلدهای خصوصی دسترسی داشته باشید. این دسترسی نباید برای تغییر مستقیم فیلدهای خصوصی کلاس پایه استفاده شود.

---

### جمع‌بندی:
به‌طور کلی، اصل LSP بیان می‌کند که هر تغییری که در زیرکلاس اعمال می‌شود باید به‌گونه‌ای باشد که استفاده از زیرکلاس‌ها به‌جای کلاس پایه بدون ایجاد مشکل ممکن باشد. این اصل از تغییرات ناسازگار جلوگیری می‌کند و به پایداری و انعطاف‌پذیری کد کمک می‌کند.
	 */
	public class Bird
	{
		public virtual void Fly()
		{
			Console.WriteLine("Flying!");
		}
	}

	public class Sparrow : Bird
	{
		// گنجشک می‌تواند پرواز کند
	}

	public class Penguin : Bird
	{
		public override void Fly()
		{
			throw new NotImplementedException("Penguins can't fly!");
		}
	}


	

}
